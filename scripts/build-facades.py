#!/usr/bin/env python3
"""Cut the photoreal building facades of the parcel story into layers for the streets scene.

Reads public/assets/parcel-story/1-street/backdrop/bld-*.avif (made earlier for the parcel story, no new AI credits), crops each to its
opaque area, writes public/assets/world/facades/f0.jpg ... and src/world/facades.js with, for each facade, how to stack it on a building of
any height: a top band, N repeated floors (one floor "slice", seam-free), and a ground band (the shopfront or lobby).
All y numbers below are pixels in the original image; they were found with scripts/ruler images and a seam search (see src/world/README.md).
Run:  python3 scripts/build-facades.py
"""
import json, os
from PIL import Image, ImageFilter

SRC = 'public/assets/parcel-story/1-street/backdrop/'
OUT = 'public/assets/world/facades/'
JS = 'src/world/facades.js'
FLOOR_M = 3.4          # one floor, in metres: sets the metres-per-pixel of every facade
LAYER = (1024, 1536)   # every facade is resampled to this size (normalised coordinates keep the proportions)

# name: (file, crop x0, x1, y0, y1, floor pitch px, slice start y, top band end y, ground band top y, minimum building height in m, comment)
FACADES = [
    ('cafe',   'bld-cafe',   16, 1009,   4, 1499, 409, 205, 205, 1031,  7.5, 'cream residential block, balconies over a glass cafe'),
    ('retail', 'bld-retail', 32, 1065,  90, 1499, 367, 208, 208,  907,  9.0, 'terracotta apartments with glass balconies over two shops'),
    ('med',    'bld-med',     9, 1122,   2, 1496, 310, 250, 250, 1040,  9.0, 'green and white cladding over a pharmacy'),
    ('it',     'bld-it',    163, 1352, 129, 1499, 260, 504, 244, 1020, 12.0, 'glass office tower with fins over a lobby'),
    ('fin',    'bld-fin',    33, 1171,   1, 1494, 200, 704, 104, 1095, 14.0, 'stone and glass office block over a lobby'),
]

os.makedirs(OUT, exist_ok=True)
rows = []
for i, (name, file, x0, x1, y0, y1, pitch, slice0, topEnd, groundTop, minH, note) in enumerate(FACADES):
    im = Image.open(SRC + file + '.avif').convert('RGBA')
    crop = im.crop((x0, y0, x1, y1))
    bg = Image.new('RGB', crop.size, (200, 200, 200)); bg.paste(crop, mask=crop.split()[3])
    # a light sharpening (the pictures are slightly soft) so the facades stay crisp when the camera comes close
    bg.resize(LAYER, Image.LANCZOS).filter(ImageFilter.UnsharpMask(radius=1.6, percent=75, threshold=2)).save(OUT + f'f{i}.jpg', 'JPEG', quality=90, optimize=True, progressive=True)
    mpp = FLOOR_M / pitch
    H = y1 - y0; W = x1 - x0
    v = lambda y: round((y - y0) / H, 5)
    rows.append({'name': name, 'file': f'/assets/world/facades/f{i}.jpg', 'widthM': round(W * mpp, 2), 'heightM': round(H * mpp, 2),
                 'vTop': v(topEnd), 'v0': v(slice0), 'vp': round(pitch / H, 5), 'vGround': v(groundTop),
                 'topM': round((topEnd - y0) * mpp, 2), 'groundM': round((y1 - groundTop) * mpp, 2), 'floorM': FLOOR_M, 'minH': minH, 'note': note})
    # a shop signboard that suits this facade's own shopfront, on its blank fascia (only where the picture has one)
    gm = rows[-1]['groundM']
    if name == 'med':
        rows[-1]['sign'] = {'names': ['MEDICALS'], 'y': round(gm - 1.55, 2), 'h': 1.05}
    elif name == 'retail':
        rows[-1]['sign'] = {'names': ['SAREES', 'TEXTILES', 'FASHION', 'GOLD HOUSE'], 'y': round(gm - 1.3, 2), 'h': 0.95}
    print(name, 'size', (W, H), 'width', rows[-1]['widthM'], 'm  top', rows[-1]['topM'], 'm  ground', rows[-1]['groundM'], 'm')

with open(JS, 'w') as f:
    f.write('/* GENERATED by scripts/build-facades.py: do not edit.\n   Photoreal building facades (from the parcel story pictures) and how to stack them on a building of any height:\n'
            '   top band (0 .. vTop), then N repeats of one floor slice (v0 .. v0 + vp, seam-free), then the ground band (vGround .. 1).\n'
            '   v is measured down the picture, 0 at the top. Sizes in metres are real-world sizes (a floor is 3.4 m). */\n')
    f.write('export const FACADES = ' + json.dumps(rows, indent=1) + ';\n')
print('wrote', JS)
